export const topicById = (id) => TOPICS.find((t) => t.id === id);

// Pick a topic, preferring ones not practised much yet.
export function pickTopic(done = {}, cat = null, rnd = Math.random) {
  const pool = TOPICS.filter((t) => !cat || t.cat === cat);
  const min = Math.min(...pool.map((t) => done[t.id] || 0));
  const fresh = pool.filter((t) => (done[t.id] || 0) === min);
  return fresh[Math.floor(rnd() * fresh.length)];
}
